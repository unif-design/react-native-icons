const fs = require('node:fs');
const path = require('node:path');
const prettier = require('prettier');
const { parseSvg } = require('./svg-parser.cjs');

const root = path.resolve(__dirname, '..');
const header = '// AUTO-GENERATED by scripts/build-icons.cjs. Do not edit.\n';

async function buildOutputs(entries) {
  const names = new Set();
  const components = new Set();
  const icons = [...entries]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((entry) => {
      const { name, component } = entry;
      if (
        !/^[a-z][a-z0-9-]*$/.test(name) ||
        !/^[A-Z][A-Za-z0-9]*(Outlined|Filled)$/.test(component)
      ) {
        throw new Error(`Invalid icon name: ${name} / ${component}`);
      }
      if (names.has(name) || components.has(component))
        throw new Error(`Duplicate icon: ${name} / ${component}`);
      names.add(name);
      components.add(component);
      let def;
      try {
        def = parseSvg(entry.svg);
      } catch (error) {
        throw new Error(`${name}: ${error.message}`, { cause: error });
      }
      const filled = def.elements.every(
        (el) => el.stroke === 'none' && el.fill === 'currentColor'
      );
      if (component.endsWith('Filled') !== filled)
        throw new Error(`Icon style does not match name: ${component}`);
      return { name, component, def };
    });
  if (!icons.length) throw new Error('Icon source is empty');

  const outputs = new Map();
  for (const { component, def } of icons) {
    outputs.set(
      `src/icons/${component}.tsx`,
      `${header}
import { createIcon } from '../createIcon';
const ${component} = /*#__PURE__*/ createIcon('${component}', ${JSON.stringify(def)});
export default ${component};
`
    );
  }
  outputs.set(
    'src/index.tsx',
    `${header}
export type { IconProps } from './types';
${icons.map(({ component }) => `export { default as ${component} } from './icons/${component}';`).join('\n')}
`
  );
  const catalog = `${header}
import { ${icons.map(({ component }) => component).join(', ')} } from '@unif/react-native-icons';
export const iconCatalog = [${icons.map(({ name, component }) => `{ name: '${component}', sourceName: '${name}', Icon: ${component} }`).join(',\n')}] as const;
`;
  outputs.set('example/src/catalog.ts', catalog);
  outputs.set('website/src/components/catalog.ts', catalog);
  const config = require('../package.json').prettier;
  for (const [file, content] of outputs)
    outputs.set(
      file,
      await prettier.format(content, { ...config, filepath: file })
    );
  return outputs;
}

async function main({ projectRoot = root, check = false } = {}) {
  const sources = path.join(projectRoot, 'src/svg');
  const manifest = JSON.parse(
    fs.readFileSync(
      path.join(projectRoot, 'scripts/icon-manifest.json'),
      'utf8'
    )
  );
  const files = fs
    .readdirSync(sources)
    .filter((file) => file.endsWith('.svg'))
    .sort();
  const sourceNames = files.map((file) => file.slice(0, -4));
  if (
    sourceNames.length !== Object.keys(manifest).length ||
    sourceNames.some((name) => !Object.hasOwn(manifest, name))
  ) {
    throw new Error(
      'SVG source and icon-manifest.json must contain exactly the same names'
    );
  }
  // Validate and format every input before changing any generated file.
  const outputs = await buildOutputs(
    sourceNames.map((name) => ({
      name,
      component: manifest[name],
      svg: fs.readFileSync(path.join(sources, `${name}.svg`), 'utf8'),
    }))
  );
  const iconsDirectory = path.join(projectRoot, 'src/icons');
  const stale = fs.existsSync(iconsDirectory)
    ? fs
        .readdirSync(iconsDirectory)
        .filter((file) => !outputs.has(`src/icons/${file}`))
    : [];
  const changed = [...outputs].filter(
    ([file, content]) =>
      !fs.existsSync(path.join(projectRoot, file)) ||
      fs.readFileSync(path.join(projectRoot, file), 'utf8') !== content
  );
  if (check) {
    if (changed.length || stale.length)
      throw new Error(
        `Generated icons are stale (${changed.length} changed, ${stale.length} removed). Run yarn generate.`
      );
    return outputs.size;
  }
  for (const file of stale) {
    if (
      !fs
        .readFileSync(path.join(iconsDirectory, file), 'utf8')
        .startsWith(header)
    )
      throw new Error(`Refusing to remove non-generated file: ${file}`);
  }
  for (const [file, content] of changed) {
    fs.mkdirSync(path.dirname(path.join(projectRoot, file)), {
      recursive: true,
    });
    fs.writeFileSync(path.join(projectRoot, file), content);
  }
  for (const file of stale) fs.unlinkSync(path.join(iconsDirectory, file));
  return outputs.size;
}

module.exports = { buildOutputs, main };
if (require.main === module)
  main({ check: process.argv.includes('--check') })
    .then((count) => {
      console.log(
        `icons: ${count - 3} components ${process.argv.includes('--check') ? 'verified' : 'generated'}`
      );
    })
    .catch((error) => {
      console.error(error.message);
      process.exitCode = 1;
    });
